/// Seven rows of five pixels for `c` (lower case is folded to upper case).
pub fn glyph(c: u8) -> [u8; GH as usize] {
    let u = c.to_ascii_uppercase();
    if u >= FIRST && u <= LAST {
        TABLE[(u - FIRST) as usize]
    } else {
        [0; GH as usize]
    }
}

/// Pixel width of `s` at the given integer scale, including one space between glyphs.
pub fn measure(s: &str, scale: u32) -> u32 {
    let n = s.chars().count() as u32;
    if n == 0 {
        0
    } else {
        n * (GW * scale + scale) - scale
    }
}
