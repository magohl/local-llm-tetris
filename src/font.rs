//! A compact 5x7 bitmap font so the renderer can draw text without any DOM/canvas help.
//!
//! Each glyph is seven rows; the low five bits of every row are the pixels, bit 4 being
//! the leftmost column.

pub const GW: u32 = 5;
pub const GH: u32 = 7;
const FIRST: u8 = b' ';
const LAST: u8 = b'Z';

